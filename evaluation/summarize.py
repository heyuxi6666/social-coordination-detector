"""Aggregate results/raw_results.csv into summary.csv, tables.md and the two figures.

    python evaluation/summarize.py [--results evaluation/results]

Reads only the CSV written by run_experiments.py.  Deterministic apart from the runtime column.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))

from bench import metrics, svgplot  # noqa: E402

NUMERIC = {"seed", "n_groups", "detected", "spurious_groups", "tp", "fp", "fn", "negatives", "any_group", "runtime_s",
           "trace_built", "trace_post_recall", "trace_post_precision", "trace_cohort_recall", "trace_runtime_s"}
MAIN_METHODS = ("A_overlap_only", "B_time_bucket", "C_v1")
METHOD_NAMES = {"A_overlap_only": "A overlap-only", "B_time_bucket": "B time-bucket", "C_v1": "C V1 (strong+moderate)",
                "C_v1_strong": "C V1 (strong only)"}
SUMMARY_FIELDS = ["experiment", "config_id", "label", "rq", "method", "n_seeds", "detect_rate", "detect_lo", "detect_hi",
                  "precision", "recall", "f1_micro", "f1_seed_mean", "f1_seed_se", "spurious_per_dataset", "account_fpr",
                  "null_fp_rate", "null_fp_lo", "null_fp_hi", "null_groups_per_dataset", "null_account_fpr",
                  "trace_built_rate", "trace_post_recall", "trace_post_precision", "runtime_ms_median"]


def read_rows(path: Path) -> list[dict]:
    rows = []
    with path.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            rows.append({k: (float(v) if k in NUMERIC and v != "" else v) for k, v in row.items()})
    return rows


def summarise_all(rows: list[dict]) -> list[dict]:
    grouped: dict[tuple, list[dict]] = defaultdict(list)
    order: list[tuple] = []
    for row in rows:
        key = (row["experiment"], row["config_id"], row["label"], row["rq"], row["method"])
        if key not in grouped:
            order.append(key)
        grouped[key].append(row)
    out = []
    for key in order:
        entry = dict(zip(("experiment", "config_id", "label", "rq", "method"), key))
        entry.update(metrics.summarise(grouped[key]))
        out.append(entry)
    return out


def fmt(value, digits: int = 2) -> str:
    if value in ("", None) or (isinstance(value, float) and math.isnan(value)):
        return "–"
    return f"{value:.{digits}f}" if isinstance(value, float) else str(value)


def interval(entry: dict, rate: str, lo: str, hi: str) -> str:
    return "–" if entry.get(rate) in ("", None) else f"{entry[rate]:.2f} [{entry[lo]:.2f}, {entry[hi]:.2f}]"


def write_summary(path: Path, summary: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=SUMMARY_FIELDS, lineterminator="\n", restval="")
        writer.writeheader()
        for entry in summary:
            writer.writerow({k: (f"{v:.4f}" if isinstance(v, float) else v) for k, v in entry.items()})


def tables(summary: list[dict], config: dict, run_info: dict) -> str:
    titles = {e["id"]: e for e in config["experiments"]}
    lines = ["# Benchmark summary tables", "",
             f"Generated by `summarize.py` from `raw_results.csv`: {run_info['configurations']} configurations x "
             f"{len(run_info['seeds'])} seeds (base seed {run_info['seeds'][0]}), {run_info['datasets']} synthetic datasets, "
             f"Python {run_info['python']}. All numbers are measured on synthetic data only.", "",
             "Reading guide: *Detected* = share of coordinated datasets where some predicted group matches the true "
             "coordinated posts (Jaccard >= 0.5), with a Wilson 95% interval. *P/R/F1* = account level, counts pooled over "
             "seeds; *F1 (mean ± SE)* = per-seed F1. *Spurious* = predicted groups that do not match, per dataset. "
             "*Acct FPR* = flagged non-coordinated accounts / all non-coordinated accounts seen. *Organic FP* = share of "
             "organic-only datasets with at least one predicted group. Runtime is the median wall-clock for one dataset "
             "(30 posts) and varies by machine.", ""]
    by_experiment: dict[str, list[dict]] = defaultdict(list)
    for entry in summary:
        by_experiment[entry["experiment"]].append(entry)
    for experiment, entries in by_experiment.items():
        meta = titles[experiment]
        lines += [f"## {experiment} ({meta['rq']}): {meta['title']}", "",
                  "| Config | Method | Detected [95% CI] | P | R | F1 | F1 (mean ± SE) | Spurious | Acct FPR | Organic FP [95% CI] | ms |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for e in entries:
            f1 = "–" if e.get("f1_seed_mean") in ("", None) else f"{e['f1_seed_mean']:.2f} ± {e['f1_seed_se']:.2f}"
            fpr = e.get("account_fpr") if e.get("account_fpr") not in ("", None) else e.get("null_account_fpr")
            spurious = e.get("spurious_per_dataset") if e.get("spurious_per_dataset") not in ("", None) else e.get("null_groups_per_dataset")
            lines.append(f"| {e['label']} | {METHOD_NAMES[e['method']]} | {interval(e, 'detect_rate', 'detect_lo', 'detect_hi')} | "
                         f"{fmt(e.get('precision'))} | {fmt(e.get('recall'))} | {fmt(e.get('f1_micro'))} | {f1} | "
                         f"{fmt(spurious)} | {fmt(fpr, 3)} | {interval(e, 'null_fp_rate', 'null_fp_lo', 'null_fp_hi')} | {fmt(e['runtime_ms_median'], 1)} |")
        traced = [e for e in entries if e["method"] == "C_v1" and e.get("trace_built_rate") not in ("", None)]
        if traced:
            lines += ["", "V1 network tracer, started from V1's first group with a fixed-offset cohort:", "",
                      "| Config | Tracer built | Coordinated posts recovered | Share of traced posts that are coordinated |", "|---|---|---|---|"]
            for e in traced:
                lines.append(f"| {e['label']} | {fmt(e['trace_built_rate'])} | {fmt(e['trace_post_recall'])} | {fmt(e['trace_post_precision'])} |")
        lines.append("")
    return "\n".join(lines)


def sweep_points(summary: list[dict], experiment: str, parameter: str, method: str, value: str):
    xs, points = [], []
    for e in summary:
        if e["experiment"] != experiment or e["method"] != method or "(organic-only)" in e["label"]:
            continue
        if not e["label"].startswith(parameter + "=") or e.get("detect_rate") in ("", None):
            continue
        xs.append(e["label"].split("=", 1)[1])
        if value == "f1":
            m, se = e["f1_seed_mean"], 1.96 * e["f1_seed_se"]
            points.append((m, max(0.0, m - se), min(1.0, m + se)))
        else:
            points.append((e["detect_rate"], e["detect_lo"], e["detect_hi"]))
    return xs, points


def panel(summary, experiment, parameter, value, title, xlabel, ylabel):
    series, labels = {}, []
    for method in MAIN_METHODS:
        labels, series[method] = sweep_points(summary, experiment, parameter, method, value)
    return {"title": title, "xlabel": xlabel, "ylabel": ylabel, "x_labels": labels, "series": series}


def figures(summary: list[dict], out_dir: Path) -> list[Path]:
    legend = {m: METHOD_NAMES[m] for m in MAIN_METHODS}
    legend["C_v1"] = "C V1 detector"
    out_dir.mkdir(parents=True, exist_ok=True)
    fig1 = svgplot.two_panel_chart(
        [panel(summary, "E1_jitter", "jitter", "f1", "(a) Timing jitter", "jitter sd per like (s)", "account F1 (mean, 95% CI)"),
         panel(summary, "E2_participation", "participation", "f1", "(b) Participation", "share of group acting per post", "account F1 (mean, 95% CI)")],
        legend, "Figure 1 (RQ2). 20 seeds per point; synthetic data; defaults: 40-account group, 6 coordinated posts, 30 posts.")
    fig2 = svgplot.two_panel_chart(
        [panel(summary, "E6_rotation", "rotation", "f1", "(a) Account rotation: account F1", "slot replacement probability", "account F1 (mean, 95% CI)"),
         panel(summary, "E6_rotation", "rotation", "detect", "(b) Account rotation: group detection", "slot replacement probability", "datasets with group detected (95% CI)")],
        legend, "Figure 2 (RQ3). 20 seeds per point; synthetic data; the new account inherits the replaced account's delay.")
    paths = [out_dir / "fig1_robustness_jitter_participation.svg", out_dir / "fig2_rotation.svg"]
    for path, text in zip(paths, (fig1, fig2)):
        path.write_bytes(text.encode("utf-8"))
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Summarise benchmark results")
    parser.add_argument("--results", type=Path, default=HERE / "results")
    parser.add_argument("--config", type=Path, default=HERE / "configs" / "experiments.json")
    args = parser.parse_args(argv)
    rows = read_rows(args.results / "raw_results.csv")
    summary = summarise_all(rows)
    write_summary(args.results / "summary.csv", summary)
    config = json.loads(args.config.read_text(encoding="utf-8"))
    run_info = json.loads((args.results / "run_info.json").read_text(encoding="utf-8"))
    (args.results / "tables.md").write_bytes((tables(summary, config, run_info) + "\n").encode("utf-8"))
    paths = figures(summary, args.results / "figures")
    print(f"summarised {len(rows)} rows -> summary.csv, tables.md, {', '.join(p.name for p in paths)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
